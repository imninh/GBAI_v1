class MockCameraService : public CameraService {
  public:
    bool initialize() override {
        GB_LOG_PLAIN("CAMERA", "mock camera active — NOT real hardware");
        return true;
    }

    CameraFrame captureJpeg() override {
        CameraFrame frame;
        frame.data = kFixtureJpeg;
        frame.length = sizeof(kFixtureJpeg);
        frame.valid = true;
        held_ = true;
        return frame;
    }

    // Nothing to free — the fixture lives in flash — but the call is still
    // tracked so the release discipline matches the real driver.
    void releaseFrame() override { held_ = false; }

    bool isHolding() const { return held_; }

  private:
    bool held_ = false;
};

